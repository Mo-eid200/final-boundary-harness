#!/usr/bin/env python3
"""Run every verification layer and write RESULTS.md.

  1. m6_final_boundary.py  single-process reference model + naive control
  2. harness.py            distributed system: real processes, crash, partition
  3. mutate.py             each defence removed from the real services
  4. model_check.py        exhaustive model check + mutation of the protocol

Run:  pip install -r requirements.txt && python3 run_all.py
Takes about 4 minutes. Exit code 0 only if every layer passes.
"""
from __future__ import annotations

import subprocess
import sys
import tempfile
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent

STEPS = [
    ("1. Single-process reference model", "m6_final_boundary.py", "REPORT.md"),
    ("2. Distributed system (real processes)", "harness.py", "REPORT.md"),
    ("3. Mutation testing of the real services", "mutate.py", "MUTATION_REPORT.md"),
    ("4. Exhaustive model check of the protocol", "model_check.py", None),
]


def main() -> int:
    parts, all_ok = ["# Results", "",
                     f"Generated by `run_all.py` on {time.strftime('%Y-%m-%d %H:%M')}.", ""], True
    with tempfile.TemporaryDirectory() as td:
        for title, script, report in STEPS:
            out = Path(td) / script.replace(".py", "")
            target = out / "MODEL_CHECK.md" if report is None else out
            if report is None:
                out.mkdir(parents=True)
            print(f"== {title}", flush=True)
            t0 = time.time()
            r = subprocess.run([sys.executable, str(HERE / script), str(target)], cwd=HERE,
                               text=True, capture_output=True)
            ok = r.returncode == 0
            all_ok &= ok
            print(f"   {'PASS' if ok else 'FAIL'} ({time.time() - t0:.0f}s)", flush=True)
            text = (out / (report or "MODEL_CHECK.md")).read_text() if ok or (
                out / (report or "MODEL_CHECK.md")).exists() else r.stdout + r.stderr
            body = text.split("\n", 1)[1] if text.startswith("#") else text
            parts += [f"## {title}: {'PASS' if ok else 'FAIL'}", "", body.strip(), ""]
    parts += [f"**Every layer passes: {all_ok}**"]
    (HERE / "RESULTS.md").write_text("\n".join(parts) + "\n")
    print(f"\nevery layer passes: {all_ok}   ->  RESULTS.md")
    return 0 if all_ok else 1


if __name__ == "__main__":
    sys.exit(main())
